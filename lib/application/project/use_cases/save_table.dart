import 'package:crab_cakes/application/active_project_repository.dart';
import 'package:crab_cakes/domain/models/db_row.dart';
import 'package:crab_cakes/infrastructure/providers/column_filter_provider.dart';
import 'package:crab_cakes/presentation/view_models/project_input.dart';
import 'package:uuid/uuid.dart';

class SaveTable {
  final ActiveProjectRepository db;

  SaveTable(this.db);

  bool _isSystemColumn(String name) {
    return name.startsWith('__') || name.startsWith(kColumnPrefixToHide);
  }


  List<DbRow>? call(TableInput table, {int? limit, int? offset}) {
    final String tableName = table.name;

    //filter out system columns
    // Manual data entry should only save user-owned fields.
    // Internal/system columns are generated by the app/database layer.
    final values = Map<String, dynamic>.from(table.toValueMap())
      ..removeWhere((columnName, _) => _isSystemColumn(columnName));

    //intentionally adding app-owned metadata for data sync purposes
    final now = DateTime.now().toUtc().toIso8601String();

    values['${kColumnPrefixToHide}row_guid'] = const Uuid().v4();
    values['${kColumnPrefixToHide}created_at'] = now;
    values['${kColumnPrefixToHide}updated_at'] = now;
    // deleted_at is left out/null for normal new rows.

    db.insertRow(tableName: tableName, values: values);

    if (limit != null) {
      final result = db.getRows(tableName, limit, offset ?? 0);
      return result;
    }

    return null;
  }
}
